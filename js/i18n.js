let currentLanguage = 'en'; // Default language is English

function getLanguage() {
    return currentLanguage;
}

function t(key, fallback = '') {
    const langDict = translations[currentLanguage] || translations['en'];
    if (langDict && langDict[key] !== undefined) {
        return langDict[key];
    }
    const enDict = translations['en'];
    if (enDict && enDict[key] !== undefined) {
        return enDict[key];
    }
    const esDict = translations['es'];
    if (esDict && esDict[key] !== undefined) {
        return esDict[key];
    }
    return fallback || key;
}

function applyTranslations() {
    // 1. Text content with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (key) {
            const translation = t(key);
            if (translation) {
                if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                    if (el.type === 'button' || el.type === 'submit') {
                        el.value = translation;
                    }
                } else {
                    el.textContent = translation;
                }
                // Fix for glitch CSS pseudo-elements (content: attr(data-text))
                if (el.hasAttribute('data-text') || el.classList.contains('glitch')) {
                    el.setAttribute('data-text', translation);
                }
            }
        }
    });

    // 2. HTML content with data-i18n-html
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (key) {
            const translation = t(key);
            if (translation) {
                el.innerHTML = translation;
                if (el.hasAttribute('data-text') || el.classList.contains('glitch')) {
                    el.setAttribute('data-text', translation);
                }
            }
        }
    });

    // 3. Placeholders with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (key) {
            const translation = t(key);
            if (translation) {
                el.setAttribute('placeholder', translation);
            }
        }
    });

    // 4. Titles with data-i18n-title
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (key) {
            const translation = t(key);
            if (translation) {
                el.setAttribute('title', translation);
            }
        }
    });

    // Update main menu language toggle text
    const btnToggleLang = document.getElementById('btn-toggle-lang-menu');
    if (btnToggleLang) {
        btnToggleLang.innerText = currentLanguage === 'en' ? '🌐 LANGUAGE: ENGLISH' : '🌐 IDIOMA: ESPAÑOL';
    }

    // Update quest text if quest is active
    if (window.state && typeof window.updateQuest === 'function') {
        window.updateQuest(window.state.currentQuest);
    }

    // Refresh Trash UI if initialized
    if (typeof window.updateTrashUI === 'function') {
        window.updateTrashUI();
    }
}

function setLanguage(lang, persist = true) {
    if (lang !== 'es' && lang !== 'en') lang = 'en';
    currentLanguage = lang;
    if (persist) {
        try {
            localStorage.setItem('darklink_lang', lang);
        } catch (e) {}
    }
    if (window.state) {
        window.state.currentLang = lang;
    }
    document.documentElement.lang = lang;
    applyTranslations();

    // Trigger custom event for other modules
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function initLanguageModal() {
    const savedLang = localStorage.getItem('darklink_lang');
    if (savedLang === 'en' || savedLang === 'es') {
        currentLanguage = savedLang;
    } else {
        currentLanguage = 'en'; // Default English
    }
    
    // Check if modal exists
    const modal = document.getElementById('modal-language-select');
    if (modal) {
        // Show modal on start
        modal.classList.remove('hidden');
        
        const btnEs = document.getElementById('btn-lang-es');
        const btnEn = document.getElementById('btn-lang-en');
        
        if (btnEn) {
            btnEn.onclick = () => {
                setLanguage('en');
                modal.classList.add('hidden');
                if (typeof window.playClickSound === 'function') window.playClickSound();
            };
        }
        if (btnEs) {
            btnEs.onclick = () => {
                setLanguage('es');
                modal.classList.add('hidden');
                if (typeof window.playClickSound === 'function') window.playClickSound();
            };
        }
    }
    
    // Quick language toggle in menu
    const btnToggleLang = document.getElementById('btn-toggle-lang-menu');
    if (btnToggleLang) {
        btnToggleLang.onclick = () => {
            const nextLang = currentLanguage === 'en' ? 'es' : 'en';
            setLanguage(nextLang);
            if (typeof window.playClickSound === 'function') window.playClickSound();
        };
    }
    
    setLanguage(currentLanguage, false);
}

// Global exports
